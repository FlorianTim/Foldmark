import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Builds the icon sprite the app references through `<use href="…#name">`.
 *
 * Source: one SVG per icon in `src/assets/icons/sprite/` (the icon pack from
 * `drafts/notes/versions/1.0/foldmark-icon-redesign-pack/` plus Foldmark's own
 * additions, all 24 × 24, stroked with `currentColor`). Output: the sprite in
 * `public/icons/foldmark-icons.svg` and the list of names as a TypeScript
 * union in `src/presentation/icons/iconNames.generated.ts`, so a typo in an
 * icon name is a type error rather than an empty box.
 *
 * A sprite rather than inline SVG in components: the app forbids `v-html`, and
 * `<use>` is the one way to draw an SVG by reference without injecting markup.
 * Run: `npm run icons:build`. Both outputs are committed and never edited.
 */
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourceDirectory = resolve(root, 'src/assets/icons/sprite');
const spritePath = resolve(root, 'public/icons/foldmark-icons.svg');
const namesPath = resolve(root, 'src/presentation/icons/iconNames.generated.ts');

const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u;

const files = (await readdir(sourceDirectory)).filter((file) => file.endsWith('.svg')).sort();
const symbols = [];
const names = [];

for (const file of files) {
  const name = basename(file, '.svg');
  if (!NAME.test(name)) throw new Error(`Icon file name is not kebab-case: ${file}`);
  const source = await readFile(resolve(sourceDirectory, file), 'utf8');
  const inner = source
    .replace(/^[\s\S]*?<svg[^>]*>/u, '')
    .replace(/<\/svg>\s*$/u, '')
    .replace(/<title>[\s\S]*?<\/title>/gu, '')
    .replace(/\s+/gu, ' ')
    .trim();
  if (/<script|on[a-z]+=|href=|xlink:/iu.test(inner)) {
    throw new Error(`Icon carries script, handlers or references: ${file}`);
  }
  symbols.push(
    `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.85" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`,
  );
  names.push(name);
}

await mkdir(resolve(root, 'public/icons'), { recursive: true });
await writeFile(spritePath, `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>\n`);
await writeFile(
  namesPath,
  [
    '// Generated by `npm run icons:build` from `src/assets/icons/sprite/`. Do not edit.',
    '',
    '/** Every icon the sprite in `public/icons/foldmark-icons.svg` defines. */',
    'export const ICON_NAMES = [',
    ...names.map((name) => `  '${name}',`),
    '] as const;',
    '',
    '/** The name of one sprite icon. */',
    'export type IconName = (typeof ICON_NAMES)[number];',
    '',
  ].join('\n'),
);
console.log(`Built the icon sprite with ${names.length} icons.`);
